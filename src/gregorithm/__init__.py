_EXPORT_MODULES = {name: module for module, names in _MODULE_EXPORTS.items() for name in names}


def __getattr__(name):
    """Load only the requested public operation, preserving existing import syntax.

    New preparation/point calculations must not initialize legacy hash/identity
    infrastructure merely because a user imports gregorithm. Optional graphics,
    notebook adapters and legacy calculation modules load only when requested.
    """
    if name not in _EXPORT_MODULES:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    value = getattr(import_module(f".{_EXPORT_MODULES[name]}", __name__), name)
    globals()[name] = value
    return value


def __dir__():
    """Expose all documented names to notebook completion without importing their modules."""
    return sorted(set(globals()) | set(__all__))
